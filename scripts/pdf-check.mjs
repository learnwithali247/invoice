/**
 * Local-only PDF verification probe.
 *
 *   node scripts/pdf-check.mjs [port]
 *
 * react-pdf is the riskiest dependency this app ships: it needs a real Node
 * runtime, builds fonts at runtime and fetches the logo over the network. It is
 * the one thing that cannot be verified by `next build`, and it is exactly what
 * breaks silently on Vercel. So this drives the actual endpoint end to end:
 *
 *   1. no logo          -> font + layout path
 *   2. with a real PNG   -> react-pdf's runtime image fetch
 *   3. a long item list  -> multi-page + repeating table header
 *   4. RLS: a second account must get 404, never another user's PDF
 *
 * Writes the generated PDF to tmp/pdf-check/ so it can be opened by eye.
 * Creates a throwaway account and deletes it again.
 */
